def quadrant(influence: int, interest: int) -> str:
    hi_inf, hi_int = influence >= 3, interest >= 3
    return {(True, True): "Управлять плотно", (True, False): "Держать удовлетворёнными",
            (False, True): "Держать в курсе", (False, False): "Наблюдать"}[(hi_inf, hi_int)]


# Доля оси для значения шкалы: 1–2 — нижняя/левая половина, 3–5 — верхняя/правая (как в quadrant())
POS = {1: 0.12, 2: 0.32, 3: 0.6, 4: 0.76, 5: 0.92}


def build_matrix_png(path: Path) -> None:
    w, h, pad = 1120, 820, 120
    img = Image.new("RGB", (w, h), "white")
    d = ImageDraw.Draw(img)
    gx0, gy0, gx1, gy1 = pad, 60, w - 40, h - pad
    mx, my = (gx0 + gx1) / 2, (gy0 + gy1) / 2
    fills = {(0, 0): "#fff3bf", (1, 0): "#ffe3e3", (0, 1): "#e9ecef", (1, 1): "#d0ebff"}
    labels = {(0, 0): "Держать удовлетворёнными", (1, 0): "Управлять плотно",
              (0, 1): "Наблюдать", (1, 1): "Держать в курсе"}
    for (cx, cy), color in fills.items():
        box = [gx0 if cx == 0 else mx, gy0 if cy == 0 else my, mx if cx == 0 else gx1, my if cy == 0 else gy1]
        d.rectangle(box, fill=color, outline="#adb5bd")
        d.text((box[0] + 10, box[1] + 8), labels[(cx, cy)], font=font(18, True), fill="#495057")
    d.text((20, 18), "Матрица «влияние — интерес» (красные — скрытые стейкхолдеры)",
           font=font(20, True), fill="#212529")
    d.text(((gx0 + gx1) / 2 - 60, gy1 + 20), "Интерес →", font=font(18, True), fill="#212529")
    d.text((12, my - 12), "Влияние ↑", font=font(18, True), fill="#212529")
    occupied: dict[tuple[int, int], int] = {}
    for i, (_, _, inf, intr, hidden, _) in enumerate(STAKEHOLDERS, 1):
        n = occupied.get((inf, intr), 0)
        occupied[(inf, intr)] = n + 1
        x = gx0 + POS[intr] * (gx1 - gx0) + n * 38 - 16
        y = gy1 - POS[inf] * (gy1 - gy0 - 40) - 16  # 40 px сверху — под подписи квадрантов
        d.ellipse([x, y, x + 32, y + 32], fill="#c92a2a" if hidden else "#1f4e79")
        d.text((x + 9 if i < 10 else x + 4, y + 6), str(i), font=font(16, True), fill="white")
    img.save(path)


