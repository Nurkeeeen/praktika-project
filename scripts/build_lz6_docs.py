"""Собирает ЛЗ 6 (прогноз сроков Монте-Карло) в .docx и .md из выполненного analytics/monte_carlo.ipynb.

Цифры и графики берутся из выходов notebook — сначала выполните python analytics/build_notebook.py.
Запуск: python scripts/build_lz6_docs.py
"""

from __future__ import annotations

import base64
import csv
import re
import sys
from pathlib import Path

import nbformat

ROOT = Path(__file__).resolve().parents[1]
AN = ROOT / "analytics"
sys.path.insert(0, str(ROOT / "scripts"))
from docgen import Doc  # noqa: E402

DOCX_OUT = ROOT / "docs" / "labs" / "ЛЗ6_Прогноз_сроков_Монте-Карло.docx"
MD_OUT = ROOT / "docs" / "lz6-forecast.md"

nb = nbformat.read(AN / "monte_carlo.ipynb", as_version=4)
texts, images = [], []
for cell in nb.cells:
    for o in cell.get("outputs", []):
        if o.get("name") == "stdout":
            texts.append(o["text"])
        if "data" in o and "image/png" in o["data"]:
            images.append(base64.b64decode(o["data"]["image/png"]))
out = "\n".join(texts)
for i, name in enumerate(["fig-throughput.png", "fig-forecast.png"]):
    (AN / name).write_bytes(images[i])


def block(label: str) -> dict:
    """Перцентили и вероятности одного сценария из вывода симуляции."""
    part = out.split(label, 1)[1].split("\n\n", 1)[0]
    ps = dict(re.findall(r"P(\d+): (\S+)", part))
    probs = re.findall(r"вероятность успеть к (M\d)[^:]*: (\d+%)", part)
    return {"ps": ps, "probs": dict(probs)}


n_mvp = re.search(r"MVP: (\d+) историй, (\d+) SP", out)
mvp = block(f"MVP ({n_mvp.group(1)} историй)")
cr = block(f"MVP после CR-001 ({int(n_mvp.group(1)) - 1})")
full = block("весь бэклог (20)")
det = re.search(r"Детерминированно: .*→ (\S+)\nПо Монте-Карло вероятность успеть к этой дате: (\d+%)", out)
hist = re.search(r"Задач за 52 недели: (\d+), в среднем ([\d.]+).*\nНедель без единой закрытой задачи: (\d+%)", out)

D = Doc()
D.title("ЛЗ 6. Вероятностный прогноз сроков MVP «Практики» (Монте-Карло)")
D.sub("Управление IT-проектами · Неделя 6 · 4 курс бакалавриата · осень 2026")
D.p("Артефакты ЗС 6: notebook с симуляцией и графиками (analytics/monte_carlo.ipynb в репозитории, выполнен, "
    "воспроизводим) и слайд «Когда будет готово» для заказчика (часть 5). Покер планирования — часть 4.")
D.note(f"Главный вывод: MVP будет готов к {mvp['ps']['50']} с вероятностью 50 % и к {mvp['ps']['85']} с "
       f"вероятностью 85 %. Запуск 01.02.2027 при текущем плане — {mvp['probs']['M4']}.")

D.h1("Часть 1. Исторические данные throughput")
D.p("Своей истории у команды ещё нет — спринты начнутся в ЗС 9. Задание разрешает взять открытый репозиторий "
    "GitHub. Мы выбрали jazzband/pip-tools: задачи там закрывает небольшая команда волонтёров, которые "
    "занимаются проектом в свободное время, как и мы между другими предметами. Крупные проекты с оплачиваемой "
    "командой закрывают 20–50 задач в неделю и дали бы бессмысленно оптимистичный прогноз.")
D.bullets([
    f"Период: 06.10.2025 – 04.10.2026 (52 недели), закрыто {hist.group(1)} задач, в среднем "
    + f"{float(hist.group(2)):.2f}".replace(".", ",") + " в неделю.",
    f"Недель без единой закрытой задачи: {hist.group(3)}. Throughput неровный: длинные паузы и всплески до 9 задач.",
    "Считаем только issues, закрытые как выполненные: без pull request, дублей и «не будем делать».",
    "Снимок выгружен скриптом analytics/fetch_throughput.py и лежит в репозитории, поэтому расчёт повторяется "
    "без интернета.",
])
D.image(AN / "fig-throughput.png", "Рис. 1. Закрытые задачи по неделям, jazzband/pip-tools")

D.h1("Часть 2. Симуляция и результат")
D.p(f"Бэклог MVP — {n_mvp.group(1)} историй ({n_mvp.group(2)} SP) релизов «ходячий скелет» и «MVP» из ЛЗ 4. "
    "В каждом из 10 000 прогонов идём по календарю с 12.10.2026. Для каждой недели случайно берём неделю из "
    "истории и учитываем календарь команды из ЛЗ 5: в неделю рубежного контроля работаем примерно вполовину, в "
    "сессию — ноль, на каникулах — 80 %. Прогон заканчивается, когда закрыты все истории. Генератор случайных "
    "чисел зафиксирован (seed 2026), поэтому результат воспроизводим.")
D.image(AN / "fig-forecast.png", "Рис. 2. Гистограмма даты готовности и кумулятивная кривая вероятности")
D.table(["Сценарий", "P50", "P70", "P85", "P95", "Успеть к M3 (18.12)", "Успеть к M4 (01.02)"], [
    [f"MVP, {n_mvp.group(1)} историй", *[mvp["ps"][p] for p in ("50", "70", "85", "95")],
     mvp["probs"]["M3"], mvp["probs"]["M4"]],
    [f"MVP после CR-001, {int(n_mvp.group(1)) - 1}", *[cr["ps"][p] for p in ("50", "70", "85", "95")],
     cr["probs"]["M3"], cr["probs"]["M4"]],
    ["Весь бэклог, 20 историй", *[full["ps"][p] for p in ("50", "70", "85", "95")],
     full["probs"]["M3"], full["probs"]["M4"]],
])
D.p("Как читать: P85 = 02.05.2027 значит, что в 85 % сценариев MVP готов не позже этой даты. Заказчику называем "
    "диапазон P50–P85, а не одну дату.")

D.h1("Часть 3. Сравнение с детерминированной оценкой")
D.p(f"План релизов ЛЗ 5 обещает весь MVP к вехе M3. Неявно это означает {n_mvp.group(2)} SP за 10 недель, то есть "
    f"около 5 SP в неделю без пауз. Так получается дата {det.group(1)}. По симуляции вероятность успеть к ней — "
    f"{det.group(2)}.")
D.table(["Причина расхождения", "Что это значит для нас"], [
    ["Среднее скрывает разброс", f"В {hist.group(3)} недель истории не закрыто ни одной задачи. План по среднему "
     "предполагает, что пустых недель не бывает."],
    ["Story points — не время", "SP измеряют относительный размер. Перевод «5 SP в неделю» не основан на данных: "
     "собственной скорости у команды пока нет."],
    ["Календарь", "Рубежные контроли, праздник 26.10 и четыре недели сессии есть в симуляции и отсутствуют в "
     "детерминированном плане."],
    ["Ожидание других", "Throughput из истории включает ожидание ревью и ответов. План предполагает, что все "
     "12 зависимостей из ЛЗ 5 подтвердят вовремя."],
    ["Совпадение с ЛЗ 5", "Capacity покрывает около 52 % работы. Монте-Карло с другой стороны приходит к той же "
     "картине: медиана — март, а не декабрь."],
])
D.p("Ограничение. Throughput взят у другой команды — это честная отправная точка, но не наша скорость. После двух "
    "спринтов (ЗС 9) меняем источник данных на выгрузку из нашего репозитория и пересчитываем. Тогда прогноз "
    "станет нашим, а не заимствованным.")

D.h1("Часть 4. Покер планирования на 10 историях")
D.note("Покер проводит команда: оценки ниже не заполнены намеренно, чтобы не выдавать придуманные цифры за "
       "результат. После игры заполните analytics/planning_poker.csv и перезапустите notebook: он сам посчитает "
       "разброс мнений.")
D.p("Правила проведения (30–40 минут):")
D.numbered([
    "Карты: 1, 2, 3, 5, 8, 13. Ведущий зачитывает историю и критерии приёмки из бэклога.",
    "Каждый выбирает карту молча, вскрываем одновременно, чтобы первая названная оценка не тянула остальных.",
    "Если оценки расходятся больше чем на одну карту, автор самой высокой и самой низкой объясняет причину. "
    "Причины записываем: это и есть главный результат покера.",
    "Второй раунд. Если согласия нет, берём большую оценку и заводим спайк на неясную часть.",
])
poker = list(csv.DictReader(open(AN / "planning_poker.csv", encoding="utf-8")))
D.table(["История", "Название", "SP в ЛЗ 4", "Раунд 1: Әлібек / Нүркен", "Почему выше / ниже", "Итог"],
        [[r["story"], r["title"], r["sp_lz4"],
          f"{r['round1_pm']} / {r['round1_ba']}" if r["round1_pm"] else "",
          " / ".join(x for x in (r["why_high"], r["why_low"]) if x), r["final_sp"]] for r in poker])
D.p("На что обратить внимание: истории с внешней зависимостью (S08 — письмо работодателю, S10 — почта "
    "вуза, S14 — образец таблицы от методиста, S16 — роли и ИБ) обычно дают самый большой разброс. Оценка "
    "зависит от того, что каждый предполагает о чужом ответе.")

D.h1("Часть 5. Слайд «Когда будет готово» для заказчика")
D.image(AN / "forecast-slide.png", "Рис. 3. Слайд для методиста и спонсора")
D.p("На слайде три вещи, которых заказчик обычно не получает: диапазон вместо даты, вероятность успеть к "
    "нужной ему дате и честный список того, что сдвинет срок в обе стороны.")

D.h1("Раскрытие использования AI")
D.p("По правилам курса: код симуляции, выбор репозитория-источника, графики и текст подготовлены с помощью "
    "AI-ассистента Claude (Anthropic). Данные выгружены из открытого API GitHub, расчёт воспроизводим. Покер "
    "планирования проводит команда; его результаты AI не генерировал. Ответственность за содержание несёт "
    "команда.")

if __name__ == "__main__":
    D.render_docx(DOCX_OUT)
    D.render_md(MD_OUT)
    print(f"saved {DOCX_OUT}\nsaved {MD_OUT}")
